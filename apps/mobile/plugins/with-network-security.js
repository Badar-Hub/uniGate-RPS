// Android network security config (docs/deployment.md §Mobile).
//
// Release builds trust only the system CA store, so a staging server behind a private CA
// (scripts/deploy/make-certs.sh) is unreachable unless the app is told about it. When
// apps/mobile/certs/ca.pem exists it is bundled as res/raw/unigate_ca and added as a trust anchor
// next to the system store; without the file the config only pins "no cleartext", which is what a
// store build should ship with. iOS needs nothing here — the CA profile is installed on the device.
const fs = require('node:fs');
const path = require('node:path');
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

const CA_FILE = path.join(__dirname, '..', 'certs', 'ca.pem');

function xml(bundledCa) {
  const anchors = bundledCa
    ? '      <certificates src="system" />\n      <certificates src="@raw/unigate_ca" />'
    : '      <certificates src="system" />';
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-network-security.js — do not edit. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false">
    <trust-anchors>
${anchors}
    </trust-anchors>
  </base-config>
</network-security-config>
`;
}

module.exports = function withNetworkSecurity(config) {
  const bundledCa = fs.existsSync(CA_FILE);
  config = withDangerousMod(config, [
    'android',
    (c) => {
      const res = path.join(c.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
      fs.mkdirSync(path.join(res, 'xml'), { recursive: true });
      fs.writeFileSync(path.join(res, 'xml', 'network_security_config.xml'), xml(bundledCa));
      if (bundledCa) {
        fs.mkdirSync(path.join(res, 'raw'), { recursive: true });
        fs.copyFileSync(CA_FILE, path.join(res, 'raw', 'unigate_ca.pem'));
      }
      return c;
    },
  ]);
  return withAndroidManifest(config, (c) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(c.modResults);
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return c;
  });
};
